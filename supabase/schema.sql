create policy bookings_read_own on public.bookings for select to authenticated
  using (created_by = auth.uid());
drop policy if exists bookings_insert_own on public.bookings;
create policy bookings_insert_own on public.bookings for insert to authenticated
  with check (created_by = auth.uid());
drop policy if exists bookings_update_own on public.bookings;
create policy bookings_update_own on public.bookings for update to authenticated
  using (created_by = auth.uid() and status = 'booked')
  with check (created_by = auth.uid() and status = 'booked');
drop policy if exists bookings_cancel_own_before_session on public.bookings;
create policy bookings_cancel_own_before_session on public.bookings for delete to authenticated
  using (created_by = auth.uid() and status = 'booked'
    and public.booking_session_starts_at(date, slot) > now());

