-- The booking window is Friday noon through Sunday 11:59 AM (Asia/Kolkata).
-- It always applies to the following Monday-Sunday booking week.
create or replace function public.current_booking_week_start(at_time timestamptz default now())
returns date
language sql
stable
as $$
  select (date_trunc('week', timezone('Asia/Kolkata', at_time)::date::timestamp)::date + 7);
$$;

create or replace function public.booking_window_open(at_time timestamptz default now())
returns boolean
language plpgsql
stable
as $$
declare
  local_time timestamp := timezone('Asia/Kolkata', at_time);
  day_number integer := extract(isodow from local_time);
begin
  return (day_number = 5 and local_time::time >= time '12:00')
      or day_number = 6
      or (day_number = 7 and local_time::time < time '12:00');
end;
$$;

create or replace function public.get_booking_context()
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  week_start date := public.current_booking_week_start();
  is_open boolean := public.booking_window_open();
begin
  return jsonb_build_object(
    'week_days', (
      select jsonb_agg(to_char(day_value::date, 'YYYY-MM-DD') order by day_value)
      from generate_series(week_start, week_start + 6, interval '1 day') as days(day_value)
    ),
    'open', is_open,
    'message', case when is_open
      then 'Booking window is open — book any available slot until Sunday 11:59 AM.'
        else 'Booking window is closed. Opens Friday 12:00 PM, closes Sunday 11:59 AM, for the upcoming week.'
    end
  );
end;
$$;

create or replace function public.booking_session_starts_at(booking_date date, booking_slot text)
returns timestamptz
language sql
immutable
as $$
  select (booking_date + split_part(booking_slot, ' - ', 1)::time) at time zone 'Asia/Kolkata';
$$;

create or replace function public.validate_booking_window()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if not public.booking_window_open() then
    raise exception 'Bookings are only accepted Friday 12:00 PM through Sunday 11:59 AM (Asia/Kolkata).';
  end if;
  if new.date < public.current_booking_week_start()
     or new.date > public.current_booking_week_start() + 6 then
    raise exception 'The booking date must be in the upcoming booking week.';
  end if;
  if new.created_by is distinct from auth.uid() then
    raise exception 'A booking must belong to the authenticated anonymous user.';
  end if;
  return new;
end;
$$;

drop trigger if exists bookings_validate_window on public.bookings;
create trigger bookings_validate_window
before insert or update on public.bookings
for each row execute function public.validate_booking_window();

create or replace function public.get_booking_availability(p_instrument_id text, p_week_start date)
returns table(date date, slot text, status text)
language sql
stable
security definer
set search_path = public
as $$
  with slots(slot) as (
    values ('09:00 - 11:00'), ('11:00 - 13:00'), ('14:00 - 16:00'), ('16:00 - 18:00')
  )
  select days::date, slots.slot,
         case when bookings.id is null then 'available' else 'booked' end
  from generate_series(p_week_start, p_week_start + 6, interval '1 day') as dates(days)
  cross join slots
  left join public.bookings
    on bookings.instrument_id = p_instrument_id
   and bookings.date = days::date
   and bookings.slot = slots.slot
   and bookings.status = 'booked'
  order by days, slots.slot;
$$;

create or replace function public.get_booking_stats(p_week_start date)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'total', count(*) filter (where status = 'booked'),
    'users', count(distinct email) filter (where status = 'booked'),
    'pending', count(*) filter (where status = 'booked'),
    'completed', count(*) filter (where status = 'completed')
  )
  from public.bookings
  where date between p_week_start and p_week_start + 6;
$$;

