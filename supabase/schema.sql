-- Histopathology booking schema for Supabase.
-- Apply this file in the Supabase SQL editor, then enable Anonymous Sign-Ins
-- under Authentication > Providers. The browser must only use the publishable key.

create extension if not exists pgcrypto;

create sequence if not exists public.booking_number_seq start with 1000;

create table if not exists public.instruments (
  id text primary key,
  name text not null,
  tagline text not null,
  icon text not null,
  sop text not null,
  sort_order integer not null unique
);

create table if not exists public.specimen_types (
  id bigint generated by default as identity primary key,
  name text not null unique,
  sort_order integer not null unique
);

create table if not exists public.sop_documents (
  id bigint generated by default as identity primary key,
  title text not null,
  file text not null unique,
  sop_no text not null unique,
  sort_order integer not null unique
);

create table if not exists public.facility_contacts (
  id bigint generated by default as identity primary key,
  role text not null,
  name text not null,
  phone text not null,
  email text not null,
  sort_order integer not null unique
);

create table if not exists public.facility_settings (
  key text primary key,
  value jsonb not null
);

create table if not exists public.bookings (
  id uuid primary key default gen_random_uuid(),
  booking_id text not null unique default ('HP-' || lpad(nextval('public.booking_number_seq')::text, 4, '0')),
  created_by uuid not null default auth.uid() references auth.users(id) on delete cascade,
  user_name text not null,
  pi_name text not null,
  phone text not null,
  email text not null,
  institution text not null default '',
  specimen_type text not null references public.specimen_types(name),
  instrument_id text not null references public.instruments(id),
  date date not null,
  slot text not null check (slot in ('09:00 - 11:00', '11:00 - 13:00', '14:00 - 16:00', '16:00 - 18:00')),
  form_filename text not null,
  status text not null default 'booked' check (status in ('booked', 'completed', 'cancelled')),
  created_at timestamptz not null default now(),
  unique (instrument_id, date, slot)
);

create index if not exists bookings_created_by_idx on public.bookings(created_by);
create index if not exists bookings_week_idx on public.bookings(date, instrument_id, slot);

