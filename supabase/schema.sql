-- Make booking INSERT/UPDATE/DELETE events available to the browser realtime
-- client. RLS still controls which rows a signed-in anonymous user can read.
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
     and not exists (
       select 1 from pg_publication_rel pr
       join pg_class c on c.oid = pr.prrelid
       join pg_namespace n on n.oid = c.relnamespace
       join pg_publication p on p.oid = pr.prpubid
       where p.pubname = 'supabase_realtime' and n.nspname = 'public' and c.relname = 'bookings'
     ) then
    alter publication supabase_realtime add table public.bookings;
  end if;
end;
$$;
